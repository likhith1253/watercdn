"""Phase 1 step 4: simulator timing report (docs/timing.md). Run on an otherwise idle machine."""
from __future__ import annotations

import argparse
import os
import platform
import time

import numpy as np
import wntr

from tle.config import load_config, problem_spec, repo_path
from tle.hydraulics.simulator import Simulator
from tle.scenarios.space import base_scenario


def time_network(cfg_path: str, n: int) -> dict:
    cfg = load_config(cfg_path)
    sim = Simulator(problem_spec(cfg))
    sim.set_scenario(base_scenario(cfg))
    rng = np.random.default_rng(0)
    X = sim.lo + rng.random((n, len(sim.lo))) * (sim.hi - sim.lo)
    sim.simulate(X[0])  # compile the numba loop
    ts = []
    for x in X:
        t0 = time.perf_counter()
        sim.simulate(x)
        ts.append(time.perf_counter() - t0)
    wn = wntr.network.WaterNetworkModel(problem_spec(cfg).inp_file)
    t0 = time.perf_counter()
    for _ in range(5):
        wntr.sim.EpanetSimulator(wn).run_sim(file_prefix=str(repo_path("results/tmp/timing")))
    t_wntr = (time.perf_counter() - t0) / 5
    return {"network": cfg["network"]["name"], "junctions": len(sim.junction_ids), "D": len(sim.lo),
            "median_s": float(np.median(ts)), "p90_s": float(np.quantile(ts, 0.9)), "wntr_epanet_s": t_wntr}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n", type=int, default=100)
    args = ap.parse_args()
    repo_path("results/tmp").mkdir(parents=True, exist_ok=True)
    rows = [time_network(c, args.n) for c in ("configs/base_net3.yaml", "configs/base_ltown.yaml")]
    lines = ["# Simulator timing", "",
             f"Generated by `scripts/timing.py` ({args.n} random decisions per network, single process).",
             f"Machine: {platform.processor()} | {os.cpu_count()} logical CPUs | Python {platform.python_version()} | "
             f"WNTR {wntr.__version__} (EPANET 2.2).", "",
             "| network | junctions | D | median s / evaluation | 90th pct s | WNTR EpanetSimulator s / run |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['network']} | {r['junctions']} | {r['D']} | {r['median_s']:.4f} | {r['p90_s']:.4f} | "
                     f"{r['wntr_epanet_s']:.3f} |")
    lines += ["", "One evaluation = one 24 h extended-period simulation (1 h steps, pressure-driven demand) through the",
              "compiled toolkit loop. Under full parallel load (15 worker processes on this laptop) the per-evaluation",
              "time is 2-4x higher because of clock throttling; campaign wall-clock times are logged per run (`wall_s`).",
              "", "Evaluations are cheap (well under 0.05 s on Net3), so the study claims evaluation efficiency and",
              "reports wall-clock time; it does not claim savings of expensive simulations."]
    repo_path("docs/timing.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
