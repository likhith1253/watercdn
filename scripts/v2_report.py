"""Generate results/v2/V2_RESULTS.md from the v2 result files (no hand-typed numbers)."""
from __future__ import annotations

import json

import pandas as pd

from tle.config import repo_path


def md(df: pd.DataFrame, cols: list[str]) -> str:
    d = df[cols].copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:.3f}")
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] +
                     ["| " + " | ".join(str(v) for v in r) + " |" for r in d.itertuples(index=False)])


def main() -> None:
    r = repo_path("results")
    L = ["# v2 results", "", "Generated by `scripts/v2_report.py`; utilities in σ_fresh units.", ""]
    ga = json.loads((r / "e1/ga_check/ga_check_summary.json").read_text(encoding="utf-8"))
    L += ["## Optimiser robustness (GA vs DE, 120 identical pairs)", "", "```",
          json.dumps({k: ga[k] for k in ("n_pairs", "GA", "DE", "spearman_U_ga_vs_de")}, indent=2), "```", ""]
    L += ["## V2-B shift-aware gate (frozen E1 predictor; E1 calibration targets)", "",
          md(pd.read_csv(r / "v2/shift_aware_gate.csv"),
             ["experiment", "group", "gate", "alpha", "domain_auc", "n_targets", "n_accepted",
              "harm_rate_among_accepted", "abstention_rate", "mean_utility", "share_oracle_captured"]), ""]
    p = pd.read_csv(r / "v2/pooled_ltown.csv")
    L += ["## V2-C pooled learning / calibration, L-Town test targets", "",
          md(p, ["train", "calibration", "n_accepted", "harm_rate_among_accepted", "abstention_rate",
                 "mean_utility", "share_oracle_captured"]), ""]
    for e in ("e4x", "e1"):
        f = pd.read_csv(r / e / "v2/monitor_final.csv")
        L += [f"## V2-A trajectory monitoring — {e.upper()} (final calibration → test)", "",
              md(f, ["variant", "g", "abort_rate", "harm_rate_among_continued", "mean_U", "mean_U_no_monitor"]), ""]
        s = pd.read_csv(r / e / "v2/monitor_resplits.csv")
        L += ["Re-splits (200, pooled calibration + test):", "",
              md(s, ["variant", "g", "mean_U", "mean_U_no_monitor", "mean_abort", "mean_harm_continued",
                     "share_splits_harm_le_alpha"]), ""]
    g = pd.read_csv(r / "e4x/phase7/gate_results.csv")
    L += ["## L-Town gate with 70 calibration targets", "",
          md(g, ["lambda_source", "alpha", "n_targets", "n_accepted", "harm_rate_among_accepted", "abstention_rate",
                 "mean_utility"]), ""]
    (r / "v2" / "V2_RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    print("written")


if __name__ == "__main__":
    main()
